input_month = int(input("Enter the month number until June: "))
if input_month == 1:
    print(f"You have entered {input_month} which is January.")
elif input_month == 2:
    print(f"You have entered {input_month} which is February.")
elif input_month == 3:
    print(f"You have entered {input_month} which is March.")
elif input_month == 4:
    print(f"You have entered {input_month} which is April.")
elif input_month == 5:
    print(f"You have entered {input_month} which is May.")
elif input_month == 6:
    print(f"You have entered {input_month} which is June.")
else:
    print(f"You have entered {input_month} which is not a valid month number until June.")