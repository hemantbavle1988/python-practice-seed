
# Declaring and intializing the variable incrementing_number to None
incrementing_number = None

# setting the intial value of incrementing_number to 0
incrementing_number = 0

print("****************** WHILE LOOP INCREMENTAL******************")
# Using while loop to print the value of incrementing_number and "Hello World" until incrementing_number is less than 10
while incrementing_number < 10:
    print(incrementing_number, "Hello World")
    incrementing_number += 1

print("****************** WHILE LOOP INCREMENTAL ENDS******************")

# Declaring and intializing the variable decrementing_number to None
decrementing_number = None

# setting the intial value of decrementing_number to 10
decrementing_number = 10

print("****************** WHILE LOOP DECREMENTAL******************")
# Using while loop to print the value of decrementing_number and "Hello World" until decrementing_number is greater than 0
while decrementing_number > 0:
    print(decrementing_number, "Hello World")
    decrementing_number -= 1
print("****************** WHILE LOOP DECREMENTAL ENDS******************")