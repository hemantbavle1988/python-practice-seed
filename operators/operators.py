## OPERATORS IN PYTHON ##

# operators in python are special symbols that perform -
# operations on variables and value(operands).

# operators are used to manipulate data, perform calculations, compare values -
# and help to control the flow of your program.

# Operators are classified as

## ARITHMETIC OPERATORS ##

# +: Addition (e.g., 5 + 3 equals 8)
print(5+3)

# -: Subtraction (e.g., 10 - 2 equals 8)
print(10-2)

# *: Multiplication (e.g., 4 * 5 equals 20)
print(4*5)

# /: Division (e.g., 12 / 3 equals 4.0, returns a float by default)
print("D :",5/2)

# //: Floor division (e.g., 5 // 2 equals 2) (integer part)2 .5(decimal part)
print("FD :",16//3)

# %: Modulo (remainder after division) (e.g., 11 % 3 equals 2)
print(11%3)

# **: Power (x to the power of y) (e.g., 2 ** 3 equals 8)
print("Ex",3**2)

